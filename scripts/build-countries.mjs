// Builds the country boundaries used by the delivery-area map from Natural
// Earth (public domain, https://www.naturalearthdata.com/). Run it only to
// refresh the data: `npm run build:countries`. The output is committed, so
// deployment needs neither Node nor network access.
import { mkdir, readFile, writeFile } from "node:fs/promises";

const TAG = "v5.1.2";
const SOURCE = `https://raw.githubusercontent.com/nvkelso/natural-earth-vector/${TAG}/geojson/ne_50m_admin_0_countries.geojson`;
const target = "web/static/vendor/natural-earth";

// Pass a local copy as the first argument to skip the download.
const raw = process.argv[2]
  ? await readFile(process.argv[2], "utf8")
  : await (await fetch(SOURCE)).text();

const CONTINENTS = [
  "Africa",
  "Asia",
  "Europe",
  "North America",
  "Oceania",
  "South America",
];

// Two decimals is about 1 km: enough to recognise a country on the map.
const round = (n) => Math.round(n * 100) / 100;
function ring(points) {
  const out = [];
  for (const [x, y] of points) {
    const p = [round(x), round(y)];
    const last = out.at(-1);
    if (!last || last[0] !== p[0] || last[1] !== p[1]) out.push(p);
  }
  return out.length >= 4 ? out : null;
}
const polygon = (rings) => {
  const outer = ring(rings[0]);
  return outer ? [outer, ...rings.slice(1).map(ring).filter(Boolean)] : null;
};

const features = [];
for (const { properties: p, geometry } of JSON.parse(raw).features) {
  // Island states that Natural Earth files under "Seven seas" get the
  // continent of their UN region; uninhabited territories and Antarctica
  // are left out because nothing is delivered there.
  const continent = CONTINENTS.includes(p.CONTINENT)
    ? p.CONTINENT
    : p.SUBREGION.startsWith("Seven seas")
      ? null
      : CONTINENTS.find((c) => c === p.REGION_UN);
  if (!continent || p.ADM0_A3 === "KAS") continue;
  const polygons = (
    geometry.type === "Polygon" ? [geometry.coordinates] : geometry.coordinates
  )
    .map(polygon)
    .filter(Boolean);
  if (!polygons.length) continue;
  features.push({
    type: "Feature",
    id: p.ADM0_A3,
    properties: { name: p.ADMIN, continent },
    geometry: { type: "MultiPolygon", coordinates: polygons },
  });
}
features.sort((a, b) => a.properties.name.localeCompare(b.properties.name));

await mkdir(target, { recursive: true });
await writeFile(
  `${target}/countries.json`,
  JSON.stringify({ type: "FeatureCollection", features }),
);
await writeFile(
  `${target}/README.txt`,
  `Country boundaries derived from Natural Earth ${TAG}, 1:50m Admin 0 - Countries.
Natural Earth data is in the public domain: https://www.naturalearthdata.com/about/terms-of-use/
Generated by scripts/build-countries.mjs: coordinates rounded to two decimals,
properties reduced to name and continent, Antarctica and uninhabited
territories removed.
`,
);
console.log(`${features.length} countries written to ${target}/countries.json`);
